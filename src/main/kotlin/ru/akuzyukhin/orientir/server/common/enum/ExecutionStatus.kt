package ru.akuzyukhin.orientir.server.common.enum

/**
 * Статусы выполнения экземпляра задачи.
 *
 * Статус присваивается автоматически системой или вручную подопечным.
 */
enum class ExecutionStatus {
    /** Ожидает выполнения - начальный статус */
    PENDING,

    /** Выполнена в пределах временного окна */
    COMPLETED,

    /** Выполнена после закрытия временного окна */
    COMPLETED_LATE,

    /** Осознанный пропуск подопечным (доступен только для LOW) */
    SKIPPED,

    /** Просрочена - временное окно закрылось без реакции */
    OVERDUE,

    /** Подопечный сообщил о невозможности выполнения */
    BLOCKED
}
package ru.akuzyukhin.orientir.server.common.enum

/**
 * Типы уведомлений в системе "Ориентир".
 *
 * Определяет причину и получателя уведомления.
 */
enum class NotificationType {
    /** Напоминание подопечному о предстоящей задаче */
    REMINDER,

    /** Уведомление куратору о пропущенной/заблокированной задаче */
    MISSED,

    /** Предупреждение куратору о превышении порога отклонений */
    WARNING,

    /** Ручное уведомление от подопечного или куратора */
    MANUAL
}
package ru.akuzyukhin.orientir.server.common.enum

/**
 * Роли пользователей в системе "Ориентир".
 *
 * Определяют уровень доступа и набор доступных функций.
 * Роль назначается при регистрации и не может быть изменена.
 */
enum class Role {
    /** Куратор - выполняет мониторинг и управление расписанием */
    CURATOR,

    /** Подопечный - выполняет задачи расписания */
    WARD
}